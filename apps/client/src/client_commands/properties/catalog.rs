static REGISTRY: OnceLock<PropertyRegistry> = OnceLock::new();

pub(super) fn registry() -> &'static PropertyRegistry {
    REGISTRY.get_or_init(|| {
        let mut registry = PropertyRegistry::default();
        registry
            .register(CLIENT_PROPERTIES)
            .expect("client property keys are unique and valid");
        registry
    })
}

pub(super) fn format_property_help_with_description(
    spec: &PropertySpec,
    description: &str,
) -> String {
    format!(
        "{}: {}{}; default {}; constraints {}; owner {}; permission {:?}; lifecycle {:?}; persistent {}; resettable {}\n{}",
        spec.key,
        match spec.value_type {
            PropertyType::Boolean => "boolean",
            PropertyType::Integer => "integer",
            PropertyType::Decimal => "decimal",
            PropertyType::Text => "text",
            PropertyType::Enumeration => "enum",
        },
        spec.unit.map_or(String::new(), |unit| format!(" ({unit})")),
        spec.default.unwrap_or("n/a"),
        spec.constraints.unwrap_or("none"),
        spec.owner,
        spec.permission,
        spec.lifecycle,
        spec.persistent,
        spec.resettable,
        description,
    )
}
