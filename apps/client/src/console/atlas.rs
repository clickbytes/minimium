use super::theme::{
    ASCII_GLYPHS, ATLAS_HEIGHT, ATLAS_WIDTH, CELL, COLUMNS, POLISH_GLYPHS, WHITE_CELL,
};

pub fn font_atlas_pixels() -> Vec<u8> {
    let mut pixels = vec![0; ATLAS_WIDTH * ATLAS_HEIGHT];
    for code in 0..ASCII_GLYPHS {
        let rows = glyph_rows(char::from_u32(code as u32).unwrap_or('?'));
        write_glyph(&mut pixels, code, rows);
    }
    for (index, character) in POLISH_GLYPHS.iter().copied().enumerate() {
        let rows = glyph_rows(character);
        write_glyph(&mut pixels, ASCII_GLYPHS + index, rows);
    }
    let white_x = (WHITE_CELL % COLUMNS) * CELL;
    let white_y = (WHITE_CELL / COLUMNS) * CELL;
    for y in 0..CELL {
        for x in 0..CELL {
            pixels[(white_y + y) * ATLAS_WIDTH + white_x + x] = 255;
        }
    }
    pixels
}

fn write_glyph(pixels: &mut [u8], code: usize, rows: [u8; 7]) {
    let cell_x = (code % COLUMNS) * CELL;
    let cell_y = (code / COLUMNS) * CELL;
    for (y, row) in rows.iter().enumerate() {
        for x in 0..5 {
            if row & (1 << (4 - x)) != 0 {
                pixels[(cell_y + y) * ATLAS_WIDTH + cell_x + x + 1] = 255;
            }
        }
    }
}

