use minimium_commands::operation::ParameterSpec;
use minimium_commands::operation::{
    CatalogEntry, DomainBinding, Effect::*, OperationKind::*, PersistenceKind, TypeRef,
};

pub(super) fn entry(name: &str) -> Option<CatalogEntry> {
    let binding = DomainBinding {
        owner: "ServerRuntime",
        scope: "Server",
        context: "resolved startup configuration",
        permission: "ServerAdmin",
        capability: None,
        source: "OwnerSnapshot",
        persistence: PersistenceKind::ServerConfig,
    };
    Some(match name {
        "server.threads" => binding.declaration(
            "server.threads",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<AutoOr<U8>>"),
            Some("lanes"),
            Query,
        ),
        "server.data_dir" => binding.declaration(
            "server.data_dir",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<Path>"),
            None,
            Query,
        ),
        "server.bind" => binding.declaration(
            "server.bind",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<IpAddr>"),
            None,
            Query,
        ),
        "server.game_port" => binding.declaration(
            "server.game_port",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<U16>"),
            Some("port"),
            Query,
        ),
        "server.max_players" => binding.declaration(
            "server.max_players",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<U16>"),
            Some("players"),
            Query,
        ),
        "server.autosave_interval" => binding.declaration(
            "server.autosave_interval",
            Property,
            &[ParameterSpec::required("value", "U64")],
            TypeRef::domain("PropertyValue<U64>"),
            Some("real monotonic seconds"),
            AuthoritativeMutation,
        ),
        "server.sky.bolid_interval" => binding.declaration(
            "server.sky.bolid_interval",
            Property,
            &[ParameterSpec::required("value", "OffOr<Interval<U64>>")],
            TypeRef::domain("PropertyValue<OffOr<Interval<U64>>>"),
            Some("simulation seconds"),
            AuthoritativeMutation,
        ),
        "server.headless" => binding.declaration(
            "server.headless",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<Bool>"),
            None,
            Query,
        ),
        "server.material_package" => binding.declaration(
            "server.material_package",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<Path>"),
            None,
            Query,
        ),
        "server.material_http_port" => binding.declaration(
            "server.material_http_port",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<U16>"),
            Some("port"),
            Query,
        ),
        "world.map" => binding.declaration(
            "world.map",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<Path>"),
            None,
            Query,
        ),
        "world.definition" => binding.declaration(
            "world.definition",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<Path>"),
            None,
            Query,
        ),
        "world.planet_config" => binding.declaration(
            "world.planet_config",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<Path>"),
            None,
            Query,
        ),
        "world.time.initial_config" => binding.declaration(
            "world.time.initial_config",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<Path>"),
            None,
            Query,
        ),
        "world.climate.initial_scenario" => binding.declaration(
            "world.climate.initial_scenario",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<Path>"),
            None,
            Query,
        ),
        "world.climate.relief_influence" => binding.declaration(
            "world.climate.relief_influence",
            Property,
            &[],
            TypeRef::domain("ConfigurationValue<UnsetOr<FiniteF64>>"),
            Some("ratio 0..1"),
            Query,
        ),
        _ => return None,
    })
}
